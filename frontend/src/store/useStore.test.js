import { beforeEach, afterEach, describe, expect, it, vi } from 'vitest'
vi.mock('../lib/api.js', () => ({ api: vi.fn() }))
vi.mock('../lib/format.js', () => ({ localTZ: () => 'UTC' }))
vi.mock('../lib/exercises.js', () => ({ registerCustom: vi.fn() }))
vi.mock('../lib/demo.js', () => ({ DEMO: false, DEMO_SEEDED: 'demo' }))
vi.mock('../lib/mobile.js', () => ({ MOBILE: false }))
let useStore, api, listeners
const user = { id: 'alice', name: 'Alice' }
const state = (revision = 4, extra = {}) => ({ _revision: revision, routines: [{ id: 'local', name: 'Local', ex: [] }], ...extra })
const deferred = () => { let resolve; const promise = new Promise(r => { resolve = r }); return { promise, resolve } }
async function load(S = state(), dirty = false, signedIn = true) {
  localStorage.setItem('gym_state_v1', JSON.stringify(S))
  if (signedIn) localStorage.setItem('gym_user', JSON.stringify(user))
  if (dirty) localStorage.setItem('gym_dirty', '1')
  ;({ useStore } = await import('./useStore.js'))
  ;({ api } = await import('../lib/api.js'))
  return useStore.getState()
}
beforeEach(() => {
  vi.resetModules(); vi.useFakeTimers()
  const storage = new Map()
  vi.stubGlobal('localStorage', { getItem: k => storage.get(k) ?? null, setItem: (k, v) => storage.set(k, String(v)), removeItem: k => storage.delete(k) })
  listeners = {}
  vi.stubGlobal('document', { visibilityState: 'visible', addEventListener: (name, fn) => { listeners[name] = fn } })
  vi.stubGlobal('window', { addEventListener: (name, fn) => { listeners[name] = fn } })
})
afterEach(() => { vi.clearAllTimers(); vi.useRealTimers(); vi.unstubAllGlobals(); vi.clearAllMocks() })
describe('revision-safe browser sync', () => {
  it('marks edits dirty before debounce and sends the acknowledged revision', async () => {
    const store = await load()
    api.mockResolvedValue({ ok: true, revision: 5, ts: 100 })
    store.update(s => { s.unit = 'lb' })
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(api).not.toHaveBeenCalled()
    await store.pushState()
    expect(JSON.parse(api.mock.calls[0][1].body)).toMatchObject({ expected_revision: 4, state: { unit: 'lb' } })
    expect(useStore.getState().S._revision).toBe(5)
    expect(localStorage.getItem('gym_dirty')).toBeNull()
  })
  it('serializes edits and keeps the latest draft dirty until its own acknowledgement', async () => {
    const store = await load(), first = deferred(), second = deferred()
    api.mockReturnValueOnce(first.promise).mockReturnValueOnce(second.promise)
    store.update(s => { s.unit = 'lb' })
    const pushed = store.pushState()
    store.update(s => { s.restSec = 120 })
    const queued = store.pushState()
    expect(api).toHaveBeenCalledTimes(1)
    first.resolve({ ok: true, revision: 5, ts: 100 })
    await vi.waitFor(() => expect(api).toHaveBeenCalledTimes(2))
    expect(useStore.getState().S).toMatchObject({ unit: 'lb', restSec: 120, _revision: 5 })
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(JSON.parse(api.mock.calls[1][1].body)).toMatchObject({ expected_revision: 5, state: { restSec: 120 } })
    second.resolve({ ok: true, revision: 6, ts: 101 })
    await Promise.all([pushed, queued])
    expect(useStore.getState().S._revision).toBe(6)
    expect(localStorage.getItem('gym_dirty')).toBeNull()
  })
  it('keeps a stale draft and stops retrying after conflict, including across reload', async () => {
    const store = await load()
    api.mockRejectedValue(Object.assign(new Error('State changed'), { code: 'STATE_CONFLICT', status: 409 }))
    store.update(s => { s.unit = 'lb' })
    await expect(store.pushState()).rejects.toMatchObject({ code: 'STATE_CONFLICT' })
    await vi.advanceTimersByTimeAsync(60000)
    expect(api).toHaveBeenCalledTimes(1)
    expect(useStore.getState().syncStatus).toBe('conflict')
    vi.resetModules()
    const reloaded = (await import('./useStore.js')).useStore.getState()
    expect(reloaded.S.unit).toBe('lb')
    expect(reloaded.syncStatus).toBe('conflict')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
  })
  it('retains dirty reloads rather than pushing over an advanced server', async () => {
    const store = await load(state(4, { unit: 'lb' }), true)
    api.mockResolvedValue({ state: state(5, { unit: 'kg' }) })
    await store.pullState()
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(useStore.getState().syncStatus).toBe('conflict')
    expect(api).toHaveBeenCalledTimes(1)
  })
  it('retries failed offline writes on reconnect', async () => {
    const store = await load()
    api.mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce({ ok: true, revision: 5 })
    store.update(s => { s.unit = 'lb' })
    await expect(store.pushState()).rejects.toThrow('offline')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    listeners.online()
    await vi.waitFor(() => expect(localStorage.getItem('gym_dirty')).toBeNull())
    expect(useStore.getState().S.unit).toBe('lb')
  })
  it('pulls by revision regardless of timestamps and preserves the device active workout', async () => {
    const active = { id: 'running', sets: [1] }, store = await load(state(4, { _ts: 900, active }))
    api.mockResolvedValue({ state: state(5, { _ts: 1, unit: 'lb', active: { id: 'other-device' } }) })
    await store.pullState()
    expect(useStore.getState().S).toMatchObject({ _revision: 5, unit: 'lb', active })
    expect(api).toHaveBeenCalledTimes(1)
  })
  it('does not restore another device active workout', async () => {
    const store = await load()
    api.mockResolvedValue({ state: state(5, { active: { id: 'other-device' } }) })
    await store.pullState()
    expect(useStore.getState().S.active).toBeNull()
  })
  it('moves guest data into an empty new profile with revision zero', async () => {
    const store = await load(state(99), false, false)
    api.mockResolvedValueOnce({ state: null }).mockResolvedValueOnce({ ok: true, revision: 1 })
    store.setUser(user)
    await store.pullState()
    expect(JSON.parse(api.mock.calls[1][1].body).expected_revision).toBe(0)
    expect(useStore.getState().S.routines[0].id).toBe('local')
    expect(useStore.getState().S._revision).toBe(1)
  })
  it('loads an existing profile on first sign-in without guest training data', async () => {
    const store = await load({}, false, false)
    api.mockResolvedValue({ state: state(7) })
    store.setUser(user)
    await store.pullState()
    expect(useStore.getState().S._revision).toBe(7)
    expect(localStorage.getItem('gym_dirty')).toBeNull()
  })
  it.each(['signOut', 'signOutAll'])('%s retains the signed-in draft if saving fails', async method => {
    const store = await load()
    store.update(s => { s.unit = 'lb' })
    api.mockRejectedValue(new Error('offline'))
    await expect(store[method]()).rejects.toThrow('offline')
    expect(useStore.getState().user).toEqual(user)
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(api).toHaveBeenCalledTimes(1)
  })
  it('explicit recovery replaces the draft only after a successful read and preserves active', async () => {
    const active = { id: 'running' }, store = await load(state(4, { unit: 'lb', active }), true)
    api.mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce({ state: state(6, { unit: 'kg' }) })
    await expect(store.reloadServerState()).rejects.toThrow('offline')
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    await store.reloadServerState()
    expect(useStore.getState().S).toMatchObject({ unit: 'kg', _revision: 6, active })
    expect(localStorage.getItem('gym_dirty')).toBeNull()
    expect(useStore.getState().syncStatus).toBe('saved')
  })
  it('resumes a dirty reload when the server revision has not advanced', async () => {
    const store = await load(state(4, { unit: 'lb' }), true)
    api.mockResolvedValueOnce({ state: state(4) }).mockResolvedValueOnce({ ok: true, revision: 5 })
    await store.pullState()
    expect(JSON.parse(api.mock.calls[1][1].body)).toMatchObject({ expected_revision: 4, state: { unit: 'lb' } })
    expect(localStorage.getItem('gym_dirty')).toBeNull()
  })
  it('uploads guest data directly after registration with revision zero', async () => {
    const store = await load(state(99), false, false)
    api.mockResolvedValue({ ok: true, revision: 1 })
    store.setUser(user)
    await store.pushState()
    expect(JSON.parse(api.mock.calls[0][1].body).expected_revision).toBe(0)
  })
  it('retains another account draft without uploading it to a new account', async () => {
    const store = await load(state(0, { unit: 'lb' }), true)
    store.setUser({ id: 'bob', name: 'Bob' })
    api.mockResolvedValue({ state: null })
    await store.pullState()
    await expect(store.pushState()).rejects.toMatchObject({ code: 'STATE_OWNER_MISMATCH' })
    expect(api).not.toHaveBeenCalled()
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_state_user')).toBe('alice')
    await store.reloadServerState()
    expect(localStorage.getItem('gym_state_user')).toBe('bob')
    expect(useStore.getState().S.routines).toEqual([])
  })
  it('binds writes to the account that owns the draft', async () => {
    const store = await load()
    store.update(s => { s.unit = 'lb' })
    api.mockResolvedValue({ ok: true, revision: 5 })
    await store.pushState()
    expect(JSON.parse(api.mock.calls[0][1].body).expected_uid).toBe('alice')
  })
  it('does not overwrite another tab draft or clear its dirty marker on acknowledgement', async () => {
    const store = await load(), write = deferred()
    store.update(s => { s.unit = 'lb' })
    api.mockReturnValueOnce(write.promise)
    const pushed = store.pushState()
    const otherDraft = JSON.stringify(state(4, { restSec: 180 }))
    localStorage.setItem('gym_state_v1', otherDraft)
    write.resolve({ ok: true, revision: 5 })
    await expect(pushed).rejects.toMatchObject({ code: 'STATE_CONFLICT' })
    expect(localStorage.getItem('gym_state_v1')).toBe(otherDraft)
    expect(localStorage.getItem('gym_dirty')).toBe('1')
  })
  it('retains the acknowledged revision when importing a backup', async () => {
    const store = await load()
    api.mockResolvedValue({ ok: true, revision: 5 })
    store.replaceState(state(99, { unit: 'lb' }), true)
    await store.pushState()
    expect(JSON.parse(api.mock.calls[0][1].body).expected_revision).toBe(4)
  })
  it.each(['signOut', 'signOutAll'])('%s keeps local data when the logout request fails', async method => {
    const store = await load()
    store.update(s => { s.unit = 'lb' })
    api.mockResolvedValueOnce({ ok: true, revision: 5 }).mockRejectedValueOnce(new Error('logout failed'))
    await expect(store[method]()).rejects.toThrow('logout failed')
    expect(useStore.getState().user).toEqual(user)
    expect(useStore.getState().S.unit).toBe('lb')
    expect(JSON.parse(localStorage.getItem('gym_state_v1')).unit).toBe('lb')
  })
  it.each(['signOut', 'signOutAll'])('%s keeps new edits made while logout is in flight', async method => {
    const store = await load(), logout = deferred()
    api.mockReturnValueOnce(logout.promise)
    const signingOut = store[method]()
    await vi.waitFor(() => expect(api).toHaveBeenCalledTimes(1))
    store.update(s => { s.unit = 'lb' })
    logout.resolve({ ok: true })
    await expect(signingOut).rejects.toThrow('Local data changed')
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
  })
  it('rejects explicit recovery if the draft changes during the read', async () => {
    const store = await load(state(), true), read = deferred()
    api.mockReturnValueOnce(read.promise)
    const reloading = store.reloadServerState()
    store.update(s => { s.unit = 'lb' })
    read.resolve({ state: state(6) })
    await expect(reloading).rejects.toThrow('Local data changed')
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
  })
  it('keeps edits when an old server does not acknowledge a revision', async () => {
    const store = await load()
    api.mockResolvedValue({ ok: true })
    store.update(s => { s.unit = 'lb' })
    await expect(store.pushState()).rejects.toThrow('did not acknowledge a revision')
    expect(useStore.getState().S._revision).toBe(4)
    expect(localStorage.getItem('gym_dirty')).toBe('1')
  })
  it('keeps settings-only drafts even when they have no training data', async () => {
    const store = await load({ _revision: 4, unit: 'lb' }, true)
    api.mockResolvedValue({ state: state(5) })
    await store.pullState()
    expect(useStore.getState().S.unit).toBe('lb')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(useStore.getState().syncStatus).toBe('conflict')
  })

  it('retries temporary lock contention and keeps the draft until saved', async () => {
    const store = await load()
    api.mockRejectedValueOnce(Object.assign(new Error('Locked'), { code: 'STATE_LOCKED', status: 423 }))
      .mockResolvedValueOnce({ ok: true, revision: 5 })
    store.update(s => { s.unit = 'lb' })
    await expect(store.pushState()).rejects.toThrow('Locked')
    expect(useStore.getState().syncStatus).toBe('error')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    await vi.advanceTimersByTimeAsync(15000)
    expect(api).toHaveBeenCalledTimes(2)
    expect(localStorage.getItem('gym_dirty')).toBeNull()
  })
  it('does not discard an edit made when the final save notifies subscribers', async () => {
    const store = await load()
    store.update(s => { s.unit = 'lb' })
    api.mockResolvedValue({ ok: true, revision: 5 })
    const unsubscribe = useStore.subscribe(next => {
      if (next.syncStatus === 'saved') { unsubscribe(); next.update(s => { s.restSec = 180 }) }
    })
    await expect(store.signOut()).rejects.toThrow('Local data changed')
    expect(localStorage.getItem('gym_dirty')).toBe('1')
    expect(useStore.getState().S.restSec).toBe(180)
    expect(api).toHaveBeenCalledTimes(1)
  })

})
